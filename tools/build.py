# ---------------------------------------------------------------- checksum
def fix_checksum(b):
    b = bytearray(b)
    b[0x7FDC:0x7FE0] = b'\xFF\xFF\x00\x00'
    # 1.5 MiB LoROM: checksum = sum(first 1 MiB) + 2 * sum(last 0.5 MiB) (mirrored to 2 MiB);
    # expanded 2 MiB: plain sum of all bytes. Header size byte $FFD7 is already $0B (2 MiB).
    if len(b) == 0x180000:
        s = sum(b[:0x100000]) + 2 * sum(b[0x100000:])
    elif len(b) == 0x200000:
        s = sum(b)
    else:
        raise SystemExit(f'STOP: unexpected ROM size {len(b):#x}')
    s &= 0xFFFF
    b[0x7FDE] = s & 0xFF; b[0x7FDF] = s >> 8
    c = s ^ 0xFFFF
    b[0x7FDC] = c & 0xFF; b[0x7FDD] = c >> 8
    return bytes(b)


def check_vanilla_checksum(rom):
    assert fix_checksum(rom) == rom, 'checksum algorithm does not reproduce the retail header'


def diff_ranges(a, b):
    out, i = [], 0
    n = min(len(a), len(b))
    while i < n:
        if a[i] != b[i]:
            j = i
            while j < n and a[j] != b[j]:
                j += 1
            out.append((i, j))
            i = j
        else:
            i += 1
    if len(b) > len(a):
        out.append((len(a), len(b)))
    return out


def snes(off):
    return 0x800000 | (off // 0x8000) << 16 | 0x8000 | (off & 0x7FFF)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--rom', default=str(ROOT / 'rom_private/Mega Man X (USA) (Rev 1).sfc'))
    ap.add_argument('--name', default='system_crash')
    ap.add_argument('--define', action='append', default=[], help='asar define (test baselines only)')
    a = ap.parse_args()
    src = load_source(a.rom)
    check_vanilla_checksum(src)
    generate(src)
    out = ROOT / 'build' / f'{a.name}.sfc'
    out.write_bytes(src + bytes([0xFF]) * (0x200000 - len(src)))   # deliberate LoROM expansion to 2 MiB
    r = subprocess.run([str(ASAR), '--fix-checksum=off'] + [f'-D{d}=1' for d in a.define] + [str(ROOT / 'src/main.asm'), str(out)],
                       capture_output=True, text=True)
    print(r.stdout, r.stderr)
    if r.returncode != 0:
        sys.exit('STOP: Asar failed')
    built = fix_checksum(out.read_bytes())
    out.write_bytes(built)
    print('Changed ranges:')
    for i, j in diff_ranges(src, built):
        print(f'  {snes(i):06X}-{snes(j - 1):06X} ({j - i} bytes)')
    bps = ROOT / 'build' / f'{a.name}.bps'
    if bps.exists():
        bps.unlink()
    srcfile = ROOT / 'build/source_verified.sfc'
    srcfile.write_bytes(src)
    r = subprocess.run([str(FLIPS), '--create', '--bps', str(srcfile), str(out), str(bps)], capture_output=True, text=True)
    print(r.stdout.strip(), r.stderr.strip())
    rt = ROOT / 'build/roundtrip.sfc'
    if rt.exists():
        rt.unlink()
    r = subprocess.run([str(FLIPS), '--apply', str(bps), str(srcfile), str(rt)], capture_output=True, text=True)
    ok = rt.exists() and rt.read_bytes() == built
    print('BPS roundtrip:', 'OK' if ok else 'FAILED', r.stdout.strip(), r.stderr.strip())
    if not ok:
        sys.exit(1)
    print('Built', out, hashes(built)['crc32'], 'BPS', bps, bps.stat().st_size, 'bytes')


if __name__ == '__main__':
    main()
