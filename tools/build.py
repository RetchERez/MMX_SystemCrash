#!/usr/bin/env python3
"""Reproducible SYSTEM CRASH build.

  python tools/build.py [--rom PATH] [--name system_crash_test]

1. Verify the source ROM (size, header, CRC32, MD5, SHA-1, SHA-256) -- refuse anything else.
2. Generate derived data from the user's own ROM into build/gen/ (never committed).
3. Assemble src/main.asm with Asar onto a copy (original never touched).
4. Fix the SNES header checksum, report every changed byte range.
5. Create a BPS with Flips, re-apply it to the verified source, compare byte-for-byte.
"""
import argparse, hashlib, shutil, subprocess, sys, zlib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ASAR = ROOT / 'tools/vendor/asar191/asar.exe'
FLIPS = ROOT / 'tools/vendor/flips-windows/flips.exe'
EXPECTED = {'size': 0x180000, 'crc32': 'DED53C64', 'md5': 'DF1CC0C8C8C4B61E3B834CC03366611C',
            'sha1': 'C65216760BA99178100A10D98457CF11496C2097',
            'sha256': 'B8F70A6E7FB93819F79693578887E2C11E196BDF1AC6DDC7CB924B1AD0BE2D32'}


def pc(addr):
    return ((addr >> 16) & 0x7F) * 0x8000 + (addr & 0x7FFF)


def hashes(b):
    return {'size': len(b), 'crc32': f'{zlib.crc32(b):08X}', 'md5': hashlib.md5(b).hexdigest().upper(),
            'sha1': hashlib.sha1(b).hexdigest().upper(), 'sha256': hashlib.sha256(b).hexdigest().upper()}


def load_source(path):
    raw = Path(path).read_bytes()
    if len(raw) % 0x8000 == 512:
        raw = raw[512:]
    h = hashes(raw)
    if h != EXPECTED:
        sys.exit(f'STOP: source ROM is not unheadered USA Rev 1.\n got {h}')
    return raw


# ---------------------------------------------------------------- generators
def dim_color(c, r=0.50, g=0.40, b=0.42):
    """Emergency lighting: dim, slightly warm. Index 0 handled by caller."""
    cr, cg, cb = c & 31, (c >> 5) & 31, (c >> 10) & 31
    return int(cr * r + 0.5) | int(cg * g + 0.5) << 5 | int(cb * b + 0.5) << 10


# Grid Down: only the tower's interior rows go dark. Verified by live row tinting
# (2026-11-24): rows 2-4 = interior walls/pipes/structure; row 5 = sunlit exterior
# girders and ladders; row 7 = sky. A power cut cannot darken daylight.
KUW_DIM_ROWS = (2, 3, 4)
KUW_SLOTS = ((0, 0x85E640), (1, 0x85E9C0))   # retail stage-07 slot 0 / slot 1 sources


def gen_dim_rows(rom, src, rows):
    o = pc(src)
    out = []
    for row in rows:
        words = [dim_color(rom[o + row * 32 + 2 * i] | rom[o + row * 32 + 2 * i + 1] << 8) for i in range(16)]
        out.append('\tdw ' + ','.join(f'${w:04X}' for w in words))
    return out


def generate(rom):
    gen = ROOT / 'build/gen'
    gen.mkdir(parents=True, exist_ok=True)
    L = ["; generated by tools/build.py from the user's ROM; do not edit", 'org $85B390']
    for slot, src in KUW_SLOTS:
        L.append(f'SC_KuwDim{slot}:\t\t; rows {KUW_DIM_ROWS} of $85:{src & 0xFFFF:04X}, dimmed')
        L += gen_dim_rows(rom, src, KUW_DIM_ROWS)
    L += ['org $86FA50', 'SC_KuwSlots:', '\tdw (SC_KuwList0&$FFFF)-$A260', '\tdw (SC_KuwList1&$FFFF)-$A260']
    for slot, src in KUW_SLOTS:
        L.append(f'SC_KuwList{slot}:')
        for row in range(8):
            if row in KUW_DIM_ROWS:
                L.append(f'\tdw (SC_KuwDim{slot}&$FFFF)+${KUW_DIM_ROWS.index(row) * 0x20:02X} : db ${row * 0x10:02X}')
            else:
                L.append(f'\tdw ${(src & 0xFFFF) + row * 0x20:04X} : db ${row * 0x10:02X}\t; original row {row}')
        L.append('\tdw $FFFF')
    (gen / 'kuw_palette.asm').write_text('\n'.join(L) + '\n')
    gen_eagle(rom, gen)
    gen_halves(rom, gen)
    gen_badge(gen)
    gen_title(gen)


# ---------------------------------------------------------------- half-power lists
